//! Compares Rust (soroban-sdk) and Zig (zig-soroban-sdk) builds of the same
//! contracts on contract size and on the cost of every call.
//!
//! Run from the repository root after building both sides:
//!   stellar contract build --out-dir out/rust ...   (see README)
//!   zig build
//!   cargo run --release
//!
//! Prints a markdown report and writes it to results/REPORT.md.

mod exec;
mod network;
mod scenarios;
mod wasm;

use std::fmt::Write as _;

use soroban_env_host::xdr::{
    ContractExecutable, ContractIdPreimage, ContractIdPreimageFromAddress, CreateContractArgsV2,
    HostFunction, InvokeContractArgs, LedgerEntryData, ScAddress, ScSymbol, ScVal, Uint256,
};

use exec::{Chain, TxReport};
use network::Network;
use scenarios::Pair;

/// Protocol the network runs; must match soroban-env-host's major version.
const PROTOCOL: u32 = 29;

struct Variant {
    name: &'static str,
    label: &'static str,
}

const VARIANTS: [Variant; 3] = [
    Variant { name: "rust", label: "Rust" },
    Variant { name: "zig-small", label: "Zig small" },
    Variant { name: "zig-safe", label: "Zig safe" },
];

fn wasm_path(variant: &Variant, pair: &Pair) -> String {
    match variant.name {
        "rust" => format!("out/rust/{}", pair.rust_wasm),
        v => format!("zig-out/{v}/{}.wasm", pair.name),
    }
}

/// Everything measured for one build of one contract.
struct Run {
    wasm: Vec<u8>,
    upload: TxReport,
    deploy: TxReport,
    calls: Vec<TxReport>,
    /// Final contract storage: (key, durability, value) for every data
    /// entry, plus the instance storage map, as XDR-comparable values.
    storage: Vec<String>,
}

fn run(net: &Network, pair: &Pair, wasm: Vec<u8>) -> Run {
    let deployer = scenarios::deployer();
    let mut chain = Chain::new(net);

    let upload = chain.run(
        HostFunction::UploadContractWasm(wasm.clone().try_into().unwrap()),
        &deployer,
    );
    chain.cache_wasm(&wasm);

    let deploy = chain.run(
        HostFunction::CreateContractV2(CreateContractArgsV2 {
            contract_id_preimage: ContractIdPreimage::Address(ContractIdPreimageFromAddress {
                address: ScAddress::Account(deployer.clone()),
                salt: Uint256([7; 32]),
            }),
            executable: ContractExecutable::Wasm(exec::wasm_hash(&wasm)),
            constructor_args: pair.constructor_args.clone().try_into().unwrap(),
        }),
        &deployer,
    );
    let ScVal::Address(contract) = deploy.result.clone() else {
        panic!("[err] deploy returned {:?}", deploy.result)
    };

    let calls = pair
        .steps
        .iter()
        .map(|s| {
            chain.run(
                HostFunction::InvokeContract(InvokeContractArgs {
                    contract_address: contract.clone(),
                    function_name: ScSymbol(s.func.try_into().unwrap()),
                    args: s.args.clone().try_into().unwrap(),
                }),
                &s.source,
            )
        })
        .collect();

    // Rust and Zig deploy to the same address (same deployer and salt), so
    // their final storage is directly comparable, apart from the wasm hash.
    let mut storage = vec![];
    for (_, (entry, ttl)) in chain.ledger.iter() {
        let LedgerEntryData::ContractData(d) = &entry.data else { continue };
        if d.contract != contract {
            continue;
        }
        match &d.val {
            ScVal::ContractInstance(inst) => {
                storage.push(format!("instance storage {:?}", inst.storage));
            }
            v => storage.push(format!("{:?} {:?} = {:?} (live until {:?})", d.durability, d.key, v, ttl)),
        }
    }

    Run { wasm, upload, deploy, calls, storage }
}

fn main() {
    let net = Network::mainnet(PROTOCOL);
    let pairs = scenarios::all();
    let mut out = String::new();

    writeln!(out, "# Rust vs Zig: size and cost\n").unwrap();
    writeln!(
        out,
        "Generated by `cargo run --release` in this repository. Costs are metered by \
         soroban-env-host {PROTOCOL} with mainnet's cost models and fee settings \
         (`harness/config/mainnet-settings.xdr`). Fees are resource fees in stroops \
         (1 XLM = 10,000,000 stroops), excluding the inclusion fee bid.\n"
    )
    .unwrap();
    writeln!(
        out,
        "- **Rust**: stellar/soroban-examples, soroban-sdk 28, built with `stellar contract build`.\n\
         - **Zig small**: zig-soroban-sdk, `ReleaseSmall` (no overflow checks).\n\
         - **Zig safe**: zig-soroban-sdk, `ReleaseSafe` (traps on overflow, like Rust's `overflow-checks = true`).\n"
    )
    .unwrap();

    let mut runs: Vec<Vec<Run>> = vec![];
    for pair in &pairs {
        let mut pair_runs = vec![];
        for v in &VARIANTS {
            let path = wasm_path(v, pair);
            let wasm = std::fs::read(&path)
                .unwrap_or_else(|_| panic!("[err] missing {path}: build both sides first"));
            eprintln!("[run] {} / {}", pair.name, v.name);
            pair_runs.push(run(&net, pair, wasm));
        }
        runs.push(pair_runs);
    }

    // -- Equivalence --
    writeln!(out, "## Equivalence check\n").unwrap();
    writeln!(
        out,
        "Each Zig build must return the same values, emit the same events and leave the same \
         storage as the Rust build, or its costs are not comparable.\n"
    )
    .unwrap();
    writeln!(out, "| Contract | Zig small | Zig safe |\n|---|---|---|").unwrap();
    let mut mismatches = String::new();
    for (pair, pr) in pairs.iter().zip(&runs) {
        let mut cells = vec![];
        for (v, r) in VARIANTS.iter().zip(pr).skip(1) {
            let diffs = compare(pair, &pr[0], r);
            if diffs.is_empty() {
                cells.push("✅ identical".to_string());
            } else {
                cells.push(format!("❌ {} difference(s)", diffs.len()));
                writeln!(mismatches, "\n**{} / {}**\n", pair.name, v.label).unwrap();
                for d in diffs {
                    writeln!(mismatches, "- {d}").unwrap();
                }
            }
        }
        writeln!(out, "| {} | {} |", pair.name, cells.join(" | ")).unwrap();
    }
    out.push_str(&mismatches);
    out.push('\n');

    // -- Size --
    writeln!(out, "## Contract size (bytes)\n").unwrap();
    writeln!(out, "| Contract | Rust | Zig small | Zig safe |\n|---|--:|--:|--:|").unwrap();
    for (pair, pr) in pairs.iter().zip(&runs) {
        let rust = pr[0].wasm.len();
        let cells: Vec<String> = pr
            .iter()
            .enumerate()
            .map(|(i, r)| if i == 0 { fmt_n(rust as i64) } else { with_pct(r.wasm.len() as i64, rust as i64) })
            .collect();
        writeln!(out, "| {} | {} |", pair.name, cells.join(" | ")).unwrap();
    }
    writeln!(out, "\nBy section (code / data / contract spec / other):\n").unwrap();
    writeln!(out, "| Contract | Rust | Zig small | Zig safe |\n|---|---|---|---|").unwrap();
    for (pair, pr) in pairs.iter().zip(&runs) {
        let cells: Vec<String> = pr
            .iter()
            .map(|r| {
                let s = wasm::sections(&r.wasm);
                format!("{} / {} / {} / {}", s.code, s.data, s.spec, s.other)
            })
            .collect();
        writeln!(out, "| {} | {} |", pair.name, cells.join(" | ")).unwrap();
    }
    out.push('\n');

    // -- Cost --
    writeln!(out, "## Cost per transaction\n").unwrap();
    writeln!(
        out,
        "Zig columns show the difference from Rust. *upload* installs the wasm, *deploy* \
         creates the contract and runs its constructor; the remaining rows are calls, in order, \
         each a separate transaction against the state left by the previous one.\n"
    )
    .unwrap();
    for (pair, pr) in pairs.iter().zip(&runs) {
        writeln!(out, "### {}\n", pair.name).unwrap();
        let mut labels = vec!["upload", "deploy"];
        labels.extend(pair.steps.iter().map(|s| s.label));
        let per_variant: Vec<Vec<&TxReport>> = pr.iter().map(reports).collect();

        for (title, metric) in [
            ("CPU instructions", (|t: &TxReport| t.cpu_insns as i64) as fn(&TxReport) -> i64),
            ("Memory bytes", |t: &TxReport| t.mem_bytes as i64),
            ("Fee (stroops)", |t: &TxReport| t.fee_total()),
        ] {
            writeln!(out, "**{title}**\n").unwrap();
            writeln!(out, "| Step | Rust | Zig small | Zig safe |\n|---|--:|--:|--:|").unwrap();
            let mut totals = [0i64; 3];
            for (i, label) in labels.iter().enumerate() {
                let vals: Vec<i64> = per_variant.iter().map(|v| metric(v[i])).collect();
                if i >= 1 {
                    for (t, v) in totals.iter_mut().zip(&vals) {
                        *t += v;
                    }
                }
                writeln!(out, "| {label} | {} |", row(&vals)).unwrap();
            }
            writeln!(out, "| **total excl. upload** | {} |\n", row(&totals)).unwrap();
        }
    }

    writeln!(out, "## Fee settings used\n").unwrap();
    writeln!(out, "```\n{:#?}\n{:#?}\n```", net.fees, net.rent).unwrap();

    print!("{out}");
    std::fs::create_dir_all("results").unwrap();
    std::fs::write("results/REPORT.md", &out).unwrap();
    eprintln!("[ok] wrote results/REPORT.md");
}

/// Upload, deploy, then every call, in order.
fn reports(r: &Run) -> Vec<&TxReport> {
    let mut v = vec![&r.upload, &r.deploy];
    v.extend(r.calls.iter());
    v
}

/// Differences in observable behavior between the Rust run and a Zig run.
fn compare(pair: &Pair, rust: &Run, zig: &Run) -> Vec<String> {
    let mut diffs = vec![];
    let mut steps = vec![("deploy", &rust.deploy, &zig.deploy)];
    for (i, s) in pair.steps.iter().enumerate() {
        steps.push((s.label, &rust.calls[i], &zig.calls[i]));
    }
    for (label, r, z) in steps {
        if r.result != z.result {
            diffs.push(format!("`{label}` returns `{:?}`, Rust returns `{:?}`", z.result, r.result));
        }
        let ev = |t: &TxReport| t.events.iter().map(|e| format!("{:?}", e.body)).collect::<Vec<_>>();
        if ev(r) != ev(z) {
            diffs.push(format!("`{label}` events differ: Zig `{:?}`, Rust `{:?}`", ev(z), ev(r)));
        }
    }
    if rust.storage != zig.storage {
        for s in &zig.storage {
            if !rust.storage.contains(s) {
                diffs.push(format!("storage only in Zig: `{s}`"));
            }
        }
        for s in &rust.storage {
            if !zig.storage.contains(s) {
                diffs.push(format!("storage only in Rust: `{s}`"));
            }
        }
    }
    diffs
}

fn row(vals: &[i64]) -> String {
    let rust = vals[0];
    let mut cells = vec![fmt_n(rust)];
    cells.extend(vals[1..].iter().map(|&v| with_pct(v, rust)));
    cells.join(" | ")
}

fn with_pct(v: i64, base: i64) -> String {
    if base == 0 {
        return fmt_n(v);
    }
    let pct = (v - base) as f64 * 100.0 / base as f64;
    format!("{} ({:+.1}%)", fmt_n(v), pct)
}

fn fmt_n(v: i64) -> String {
    let s = v.unsigned_abs().to_string();
    let mut out = String::new();
    for (i, c) in s.chars().enumerate() {
        if i > 0 && (s.len() - i) % 3 == 0 {
            out.push(',');
        }
        out.push(c);
    }
    if v < 0 { format!("-{out}") } else { out }
}
